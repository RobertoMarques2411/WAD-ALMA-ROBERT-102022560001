// COMPLETE CHILD ASSESSMENT
// ======================================================

export function assessChildGrowth({
    sex,
    age,
    weight,
    lengthHeight
}) {
    // Validasi input
    if (!sex || age == null) {
        return {
            error: "Sex and age are required",
            weightForAge: null,
            lengthHeightForAge: null,
            weightForHeight: null,
            bmiForAge: null
        };
    }

    // Konversi sex ke format yang benar
    const normalizedSex = sex === 'male' || sex === 'boy' || sex === 'boys' ? 'boys' : 'girls';

    // Validasi usia
    if (age < 0 || age > 60) {
        return {
            error: "Age must be between 0 and 60 months",
            weightForAge: null,
            lengthHeightForAge: null,
            weightForHeight: null,
            bmiForAge: null
        };
    }

    const result = {
        weightForAge: null,
        lengthHeightForAge: null,
        weightForHeight: null,
        bmiForAge: null
    };

    // -------------------------------
    // Weight-for-Age (0-60 bulan)
    // -------------------------------
    if (weight != null && weight > 0) {
        const z = calculateIndicatorZScore({
            sex: normalizedSex,
            indicator: "weightForAge",
            age: Math.min(age, 24), // Weight-for-Age hanya sampai 24 bulan
            measurement: weight
        });

        result.weightForAge = {
            zScore: z,
            classification: classifyWeightForAge(z)
        };
    }

    // -------------------------------
    // Length/Height-for-Age
    // -------------------------------
    if (lengthHeight != null && lengthHeight > 0) {
        let indicator;
        let ageForReference = age;

        // < 24 bulan pakai Length-for-Age
        if (age < 24) {
            indicator = "lengthForAge";
            ageForReference = Math.min(age, 24);
        }
        // >= 24 bulan pakai Height-for-Age
        else {
            indicator = "heightForAge";
            ageForReference = Math.min(Math.max(age, 24), 60);
        }

        const z = calculateIndicatorZScore({
            sex: normalizedSex,
            indicator: indicator,
            age: ageForReference,
            measurement: lengthHeight
        });

        result.lengthHeightForAge = {
            zScore: z,
            classification: classifyLengthHeightForAge(z)
        };
    }

    // -------------------------------
    // Weight-for-Length/Height
    // -------------------------------
    if (weight != null && weight > 0 && lengthHeight != null && lengthHeight > 0) {
        let indicator;

        // < 24 bulan pakai Weight-for-Length
        if (age < 24) {
            indicator = "weightForLength";
        }
        // >= 24 bulan pakai Weight-for-Height
        else {
            indicator = "weightForHeight";
        }

        const z = calculateIndicatorZScore({
            sex: normalizedSex,
            indicator: indicator,
            age: lengthHeight, // Gunakan panjang/tinggi sebagai referensi
            measurement: weight
        });

        result.weightForHeight = {
            zScore: z,
            classification: classifyWeightForHeight(z)
        };
    }

    // -------------------------------
    // BMI-for-Age
    // -------------------------------
    if (weight != null && weight > 0 && lengthHeight != null && lengthHeight > 0) {
        const heightMeter = lengthHeight / 100;

        if (heightMeter > 0) {
            const bmi = weight / (heightMeter * heightMeter);

            const z = calculateIndicatorZScore({
                sex: normalizedSex,
                indicator: "bmiForAge",
                age: Math.min(Math.max(age, 0), 60),
                measurement: bmi
            });

            result.bmiForAge = {
                bmi: bmi,
                zScore: z,
                classification: classifyBMIForAge(z)
            };
        }
    }

    return result;
}

