// ======================================================
// WHO LMS Z-SCORE
// ======================================================

export function calculateZScore(value, L, M, S) {
    if (
        value == null ||
        L == null ||
        M == null ||
        S == null ||
        value <= 0 ||
        M <= 0 ||
        S <= 0
    ) {
        return null;
    }

    if (L === 0) {
        return Math.log(value / M) / S;
    }

    return (((value / M) ** L) - 1) / (L * S);
}

